"""
Markdown report templates for Retail BI Analyst.
"""

from __future__ import annotations

from typing import Dict
from src.reports.safety import markdown_cell

from src.core.analytics import KPIResult, RFMScores


def build_markdown_report_content(kpi: KPIResult, rfm: Dict[str, RFMScores]) -> str:
    """
    Build a professional Markdown report from metrics.

    Структура:
    - Заголовок и краткий обзор.
    - TOC c якорями разделов.
    - Таблица KPI.
    - Таблица RFM.
    - Интерпретация и рекомендации.
    """
    lines: list[str] = []

    # --- Header and overview ---
    lines.append("# Retail BI: Sales report")
    lines.append("")
    lines.append("Generated by **Retail BI Analyst**.")
    lines.append("")

    # --- Table of contents (anchors) ---
    lines.append("## Contents")
    lines.append("")
    lines.append("- [KPI overview](#kpi-overview)")
    lines.append("- [RFM analysis](#rfm-analysis)")
    lines.append("- [Insights and recommendations](#insights-and-recommendations)")
    lines.append("")

    # --- KPI section ---
    lines.append("## KPI overview")
    lines.append("")
    lines.append("| Metric | Value | Description |")
    lines.append("| ------ | ----- | ----------- |")
    lines.append(
        f"| Total revenue | **{kpi.total_revenue:,.2f}** | Sum of all transactions |"
    )
    lines.append(
        f"| Average bill | **{kpi.avg_ticket:,.2f}** | Mean order value |"
    )
    lines.append(
        f"| Transactions | **{kpi.transactions_count}** | Number of orders |"
    )
    lines.append(
        f"| Unique customers | **{kpi.unique_customers}** | Distinct customer IDs |"
    )
    lines.append(
        f"| Avg orders per customer | **{kpi.avg_transactions_per_customer:.2f}** | "
        "Customer activity intensity |"
    )
    lines.append(
        f"| Revenue per customer | **{kpi.revenue_per_customer:,.2f}** | "
        "Average CLV proxy per customer |"
    )
    lines.append(
        f"| New customers | **{kpi.new_customers_count}** | First-time buyers in period |"
    )
    lines.append(
        f"| Returning customers | **{kpi.returning_customers_count}** | Repeat buyers |"
    )
    lines.append(
        f"| Repeat-customer share | **{kpi.repeat_customer_share:.1%}** | "
        "Share of customers with ≥2 orders |"
    )
    lines.append(
        f"| Max bill | **{kpi.max_ticket:,.2f}** | Highest single order value |"
    )
    lines.append(
        f"| Min bill | **{kpi.min_ticket:,.2f}** | Lowest single order value |"
    )
    lines.append(
        f"| Median bill | **{kpi.median_ticket:,.2f}** | Typical order value |"
    )
    lines.append(
        f"| Std dev of bill | **{kpi.std_ticket:,.2f}** | Variability of order values |"
    )
    if kpi.first_order_date and kpi.last_order_date:
        lines.append(
            f"| Observation period | **{kpi.days_span} days** | "
            f"From {kpi.first_order_date:%Y-%m-%d} "
            f"to {kpi.last_order_date:%Y-%m-%d} |"
        )
        lines.append(
            f"| Revenue per day | **{kpi.revenue_per_day:,.2f}** | "
            "Average daily revenue |"
        )
        lines.append(
            f"| Revenue per month | **{kpi.revenue_per_month:,.2f}** | "
            "Average monthly revenue (approx.) |"
        )
    lines.append("")

    # --- RFM section ---
    lines.append("## RFM analysis")
    lines.append("")
    lines.append(
        "Each row represents a customer with recency, frequency, monetary, "
        "and RFM segment assignment."
    )
    lines.append("")
    lines.append("| Customer | Recency (days) | Frequency | Monetary | Segment |")
    lines.append("| -------- | -------------- | --------- | -------- | ------- |")

    for cid, scores in rfm.items():
        lines.append(
            f"| {markdown_cell(cid)} | {scores.recency_days} | {scores.frequency} | "
            f"{scores.monetary:,.2f} | {markdown_cell(scores.segment)} |"
        )

    lines.append("")

    # --- Insights and recommendations ---
    lines.append("## Insights and recommendations")
    lines.append("")

    total_customers = len(rfm)

    if total_customers == 0 or kpi.transactions_count == 0 or kpi.total_revenue == 0:
        lines.append(
            "- The current dataset does not contain enough customer-level activity "
            "to support reliable segmentation. Focus on increasing data volume "
            "and observation period before drawing strategic conclusions."
        )
        return "\n".join(lines)

    # segment distribution
    segment_counts: Dict[str, int] = {}
    for scores in rfm.values():
        segment_counts[scores.segment] = segment_counts.get(scores.segment, 0) + 1

    best_count = segment_counts.get("Best", 0)
    loyal_count = segment_counts.get("Loyal", 0)
    at_risk_count = segment_counts.get("At risk", 0)
    regular_count = segment_counts.get("Regular", 0)

    def share(count: int) -> float:
        return (count / total_customers * 100.0) if total_customers > 0 else 0.0

    best_share = share(best_count)
    loyal_share = share(loyal_count)
    at_risk_share = share(at_risk_count)
    regular_share = share(regular_count)

    # общий обзор
    lines.append(
        f"- The analyzed period includes **{kpi.transactions_count}** transactions "
        f"from **{kpi.unique_customers}** unique customers, generating a total "
        f"revenue of **{kpi.total_revenue:,.2f}** and an average bill of "
        f"**{kpi.avg_ticket:,.2f}**."
    )

    # рекомендации по сегментам
    if best_count > 0:
        lines.append(
            f"- High-value buyers in the **Best** segment represent approximately "
            f"**{best_share:.0f}%** of the active customer base. This core group "
            "warrants priority service, personalized offers and early access to "
            "new products to protect its contribution to revenue."
        )

    if at_risk_count > 0:
        lines.append(
            f"- Customers classified as **At risk** account for roughly "
            f"**{at_risk_share:.0f}%** of the base. This indicates a tangible "
            "churn exposure. Launch targeted win-back campaigns (time-limited "
            "discounts, reminder emails, reactivation bundles) to reduce "
            "potential revenue loss."
        )

    if loyal_count > 0:
        lines.append(
            f"- The **Loyal** segment, representing about **{loyal_share:.0f}%** "
            "of customers, forms a natural pipeline into the Best segment. "
            "Structured loyalty programs, upsell paths and cross-selling of "
            "higher-margin products can systematically lift their value."
        )

    if regular_count > 0:
        lines.append(
            f"- Regular customers (~**{regular_share:.0f}%** of the base) provide "
            "broad volume but still have room for frequency and basket expansion. "
            "Use simple bundles, targeted messaging and frictionless promotions "
            "to convert part of this group into Loyal buyers."
        )

    lines.append(
        "- Track how the distribution across Best, Loyal, Regular and At risk "
        "segments evolves over time. A shift towards Best and Loyal indicates "
        "effective retention and value management, while growth in At risk "
        "requires immediate corrective action."
    )
    lines.append(
        "- Combine RFM trends with product-level analytics (top categories, "
        "margins, seasonality) to adjust pricing, assortment and service design "
        "in a data-driven way, rather than relying on intuition alone."
    )

    return "\n".join(lines)