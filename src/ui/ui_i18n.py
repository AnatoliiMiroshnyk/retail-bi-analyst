def tr(lang: str, key: str) -> str:
    """
    Translation helper with fallback to English.

    If key is missing in selected language, falls back to English,
    otherwise returns key itself.
    """
    if lang in UI_TEXTS and key in UI_TEXTS[lang]:
        return UI_TEXTS[lang][key]
    return UI_TEXTS["en"].get(key, key)